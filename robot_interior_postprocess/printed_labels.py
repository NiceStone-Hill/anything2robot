def union(items):
    return md.Manifold.batch_boolean(list(items), md.OpType.Add)


def box(size, at=(0, 0, 0)):
    return md.Manifold.cube(size).translate(at)


def text_solid(label, x, y, z, pixel=0.55, depth=0.6):
    pixels = []
    for index, char in enumerate(label):
        for row, values in enumerate(FONT[char]):
            for col, value in enumerate(values):
                if value == "1":
                    # Small overlaps join adjacent pixels into continuous strokes.
                    pixels.append(
                        box(
                            [pixel + 0.015, pixel + 0.015, depth + 0.1],
                            [
                                x + (index * 6 + col) * pixel,
                                y + (6 - row) * pixel,
                                z - 0.1,
                            ],
                        )
                    )
    return union(pixels)
